export const getTranslation = (language, key) => {
  const keys = key.split('.');
  let value = TRANSLATIONS[language] || TRANSLATIONS['fr']; // Use TRANSLATIONS
  
  for (const k of keys) {
    value = value?.[k];
    if (!value) {
      // Fallback to French if translation not found
      value = TRANSLATIONS['fr']; // Use TRANSLATIONS
      for (const fallbackKey of keys) {
        value = value?.[fallbackKey];
        if (!value) return key;
      }
      break;
    }
  }
  
  return value || key;
};